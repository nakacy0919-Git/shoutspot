import fs from 'node:fs'; import assert from 'node:assert/strict';
const js=fs.readFileSync('js/v6.js','utf8'),html=fs.readFileSync('index.html','utf8'),css=fs.readFileSync('css/v6.css','utf8');
const line=js.match(/const pictures=`([^`]+)`\.split\(';'/)?.[1];assert(line,'picture dataset');
const rows=line.split(';').map(x=>x.split('|'));assert(rows.length>=100,`Expected >=100 icons, got ${rows.length}`);
assert.equal(new Set(rows.map(x=>x[0])).size,rows.length,'Emoji unique');
assert(rows.every(x=>x.length===4&&x.every(Boolean)),'Each picture has emoji, JA, EN, category');
assert(html.includes('value="ja" selected'),'Japanese default');
assert(html.includes('id="first"')&&html.includes('id="second"'),'manual reveal controls');
assert(js.includes("setPhase('waiting')")&&js.includes("setPhase('entering')")&&js.includes("setPhase('playing')"),'phase transitions');
assert(js.includes("state.round++;nextRound();"),'auto next');
assert(js.includes('state.scores[player]--'),'foul deduction');
assert(css.includes('.scoreplate{')&&css.includes('rotate(90deg)')&&css.includes('rotate(-90deg)'),'opposing orientation');
console.log(`PASS: ${rows.length} distinct icons, Japanese default, manual reveal, READY/GO, automatic next, +1/-1, opposing player rotation.`);
